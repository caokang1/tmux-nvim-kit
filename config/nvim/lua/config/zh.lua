local prefixes = {
  { "^Toggle ", "开关" },
  { "^Enable ", "开启" },
  { "^Disable ", "关闭" },
  { "^Next ", "下一个" },
  { "^Prev ", "上一个" },
  { "^Previous ", "上一个" },
}

local suffixes = {
  { " %(Root Dir%)$", "（项目根目录）" },
  { " %(root dir%)$", "（项目根目录）" },
  { " %(cwd%)$", "（当前目录）" },
  { " %(Trouble%)$", "（Trouble 面板）" },
}

function M.translate(desc)
  if type(desc) ~= "string" or desc == "" then
    return desc
  end
  local hit = M.exact[desc]
  if hit then
    return hit
  end
  -- 没有说明的分组显示为 "3 keymaps"
  local n = desc:match("^(%d+) keymaps?$")
  if n then
    return n .. " 个快捷键"
  end
  for _, p in ipairs(prefixes) do
    local rest = desc:gsub(p[1], "", 1)
    if rest ~= desc then
      local n = M.noun[rest] or M.exact[rest]
      if n then
        return p[2] .. n
      end
    end
  end
  for _, s in ipairs(suffixes) do
    local base = desc:gsub(s[1], "", 1)
    if base ~= desc and M.exact[base] then
      return M.exact[base] .. s[2]
    end
  end
  return desc
end

return M
